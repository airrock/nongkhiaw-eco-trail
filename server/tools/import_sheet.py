#!/usr/bin/env python3
"""Turns the Google Sheet "Report" (downloaded as .xlsx) into SQL for the new database.

  uv run --with openpyxl python3 server/tools/import_sheet.py ~/nongkhiaw-work/export/report.xlsx ~/nongkhiaw-work/export/import.sql

Writes the SQL file and prints a check report (counts and sums on the Sheet's side, and what was left out and why).
The .xlsx and the .sql hold guest data: keep both outside the repository. The SQL empties the booking tables first,
so it can be run again until the switch; it never touches the users table.
"""
import sys, re, json, secrets, datetime as dt
from collections import Counter
import openpyxl

src, out = sys.argv[1], sys.argv[2]
wb = openpyxl.load_workbook(src, read_only=True, data_only=True)
report = []; skipped = Counter()

def rows(tab, header_row=1):
    """Rows of a tab as dicts keyed by the header text."""
    ws = wb[tab]; it = ws.iter_rows(min_row=header_row, values_only=True)
    head = [str(c).strip() if c is not None else '' for c in next(it, ())]
    for r in it:
        d = {h: (r[i] if i < len(r) else None) for i, h in enumerate(head) if h}
        if any(v not in (None, '') for v in d.values()): yield d
def s(v, n=None):
    if v is None: return ''
    if isinstance(v, float) and v.is_integer(): v = int(v)
    if isinstance(v, (dt.datetime, dt.date)): v = v.strftime('%Y-%m-%d')
    v = str(v).strip().lstrip("'") if str(v).startswith("'") else str(v).strip()
    if n and len(v) > n: skipped[f'text cut to fit a column of {n} characters (longest was {len(v)})'] += 1; v = v[:n]
    return v
def date(v):
    if isinstance(v, dt.datetime): return v.strftime('%Y-%m-%d')
    if isinstance(v, dt.date): return v.isoformat()
    m = re.match(r'^(\d{1,2})/(\d{1,2})/(\d{4})$', s(v))
    return f'{m[3]}-{int(m[2]):02d}-{int(m[1]):02d}' if m else None
def stamp(v):   # Sheet times are Lao time (UTC+7); the database keeps UTC
    if isinstance(v, dt.datetime): return (v - dt.timedelta(hours=7)).strftime('%Y-%m-%d %H:%M:%S')
    d = date(v); return d + ' 05:00:00' if d else None
def num(v):
    try: return float(str(v).replace(',', '')) if v not in (None, '') else 0.0
    except ValueError: return 0.0
def yes(v): return 1 if s(v).lower() in ('yes', 'true', '1') or v is True else 0
def tour(v):
    t = s(v, 5)
    return t.zfill(3) if t.isdigit() else t
def receipt_no(v):
    t = s(v, 10)
    return t.zfill(6) if t.isdigit() else t
def q(v):
    if v is None: return 'NULL'
    if isinstance(v, (int, float)): return repr(int(v)) if float(v).is_integer() else repr(round(v, 2))
    return "'" + str(v).replace('\\', '\\\\').replace("'", "''").replace('\n', '\\n').replace('\r', '') + "'"

sql = ['-- Generated by server/tools/import_sheet.py. Holds guest data: do not commit.', 'SET NAMES utf8mb4;', 'SET FOREIGN_KEY_CHECKS=0;']
for t in ['travellers', 'payments', 'receipts', 'agreements', 'bookings', 'inquiries', 'reviews', 'lunch_menu', 'content', 'tour_days', 'tour_addons', 'tour_costs',
          'tour_accounts', 'agency_share', 'tours', 'change_log']:
    sql.append(f'TRUNCATE {t};')
sql.append('SET FOREIGN_KEY_CHECKS=1;')
def insert(table, cols, data):
    for i in range(0, len(data), 200):
        sql.append(f'INSERT INTO {table} ({", ".join("`" + c + "`" for c in cols)}) VALUES\n' + ',\n'.join('(' + ', '.join(q(v) for v in r) + ')' for r in data[i:i + 200]) + ';')

# ---------- settings, tours, menu, plans ----------
ws = wb['Settings']; cell = {}
for i, r in enumerate(ws.iter_rows(min_row=1, max_row=20, max_col=6, values_only=True), 1): cell[i] = r
tours = [(tour(r[0]), s(r[1], 120), num(r[2]), i) for i, r in sorted(cell.items()) if i >= 2 and r[0] not in (None, '') and s(r[1])]
insert('tours', ['code', 'name', 'price_usd', 'sort'], tours)
F = lambda row: cell.get(row, (None,) * 6)[5]
for key, row in [('transfer_one_kip', 2), ('transfer_round_kip', 3), ('train_extra_kip', 4), ('kip_per_usd', 8), ('business_name', 9), ('business_address', 10),
                 ('business_contact', 11), ('logo_url', 12), ('transport_manager', 13)]:
    v = s(F(row))
    if v: sql.append(f"UPDATE settings SET value = {q(v)} WHERE `key` = {q(key)};")
rate = num(F(8)) or 22500
menu = [(yes(r.get('Show')), s(r.get('Group'), 80), s(r.get('Dish'), 80), s(next((v for k, v in r.items() if k.startswith('Choices')), ''), 300), num(r.get('Price kip')), i)
        for i, r in enumerate(rows('Lunch menu'), 1) if s(r.get('Dish'))]
seen = set(); menu = [m for m in menu if not (m[2] in seen or seen.add(m[2]))]
insert('lunch_menu', ['show', 'grp', 'dish', 'choices', 'price_kip', 'sort'], menu)
days, addons, costs = [], [], []
for r in wb['Tour plans'].iter_rows(min_row=3, max_col=12, values_only=True):
    r = list(r) + [None] * 12
    if r[0] not in (None, '') and s(r[2]): days.append((tour(r[0]), int(num(r[1])) or 1, s(r[2])))
    if r[4] not in (None, '') and s(r[5]): addons.append((tour(r[4]), s(r[5], 200), int(num(r[6])) or None))
    if r[7] not in (None, '') and s(r[8]): costs.append((tour(r[7]), s(r[8], 200), num(r[9]), s(r[10], 20) or 'group', num(r[11]) or 1))
insert('tour_days', ['tour', 'day', 'plan'], list({(d[0], d[1]): d for d in days}.values()))
insert('tour_addons', ['tour', 'addon', 'starts_day'], list({a[0]: a for a in addons}.values()))
insert('tour_costs', ['tour', 'item', 'unit_kip', 'counted_per', 'qty'], costs)

# ---------- bookings and travellers ----------
STATUS = {'Requested', 'Confirmed', 'Paid', 'Cancelled', 'No-show'}
bookings, ids = [], set()
for r in rows('Bookings'):
    bid = s(r.get('Booking ID'))
    if not bid: continue
    if bid.upper().startswith('SELFTEST'): skipped['test bookings (SELFTEST-)'] += 1; continue
    if not re.match(r'^[A-Za-z0-9-]{4,20}$', bid): skipped['bookings with an ID the system cannot store'] += 1; continue
    if bid in ids: skipped['bookings whose ID is in the Sheet twice (first kept)'] += 1; continue
    ids.add(bid)
    st = s(r.get('Status')); st = st if st in STATUS else 'Requested'
    bookings.append({'row': (bid, stamp(r.get('Submitted at')) or '2025-01-01 00:00:00', date(r.get('Tour date')), tour(r.get('Tour')), s(r.get('Tour name'), 120),
        s(r.get('Transfer'), 400) or 'No', date(r.get('Pickup date')), date(r.get('Return date')), yes(r.get('Train station drop-off')), s(r.get('Accommodation'), 120),
        s(r.get('Maps link'), 300), s(r.get('Pickup in Nong Khiaw'), 120), s(r.get('Payment method'), 40), s(r.get('Source'), 40), s(r.get('Referrer'), 120),
        s(r.get('Site language'), 5), s(r.get('Note')), num(r.get('Est. tour USD')), num(r.get('Est. transfer kip')), st, s(r.get('Staff notes')), s(r.get('WhatsApp no'), 40),
        s(r.get('Vehicle to Nong Khiaw'), 120), s(r.get('Vehicle to Luang Prabang'), 120), s(r.get('Transport remark'), 300), s(r.get('Viewpoint'), 120),
        s(r.get('Additional package'), 200), yes(r.get('Private tour')), ''),
        'id': bid, 'status': st, 'receipt': receipt_no(r.get('Receipt No')), 'paid': num(r.get('Amount paid USD')), 'tour_usd': num(r.get('Est. tour USD')),
        'transfer_kip': num(r.get('Est. transfer kip')), 'day': date(r.get('Tour date')) or (stamp(r.get('Submitted at')) or '2025-01-01')[:10]})
insert('bookings', ['id', 'submitted_at', 'tour_date', 'tour', 'tour_name', 'transfer', 'pickup_date', 'return_date', 'train_dropoff', 'accommodation', 'maps_link', 'nk_pickup',
    'payment_method', 'source', 'referrer', 'site_language', 'note', 'est_tour_usd', 'est_transfer_kip', 'status', 'staff_notes', 'whatsapp', 'vehicle_to_nk', 'vehicle_to_lpb',
    'transport_remark', 'viewpoint', 'addon_package', 'private_tour', 'receipt_ref'], [b['row'] for b in bookings])

travellers, seen, lunch_kip = [], set(), Counter()
for r in rows('Travellers'):
    bid = s(r.get('Booking ID')); n = int(num(r.get('Traveller #')))
    if not bid or bid.upper().startswith('SELFTEST'): continue
    if bid not in ids: skipped['travellers whose booking is not in Bookings'] += 1; continue
    if n < 1 or (bid, n) in seen:
        n = 1 + max([x[1] for x in seen if x[0] == bid] or [0]); skipped['travellers renumbered (number missing or used twice)'] += 1
    seen.add((bid, n))
    m = re.match(r'^(.*?)(?:\s*\((.*)\))?$', s(r.get('Takeaway lunch')))
    ts = s(r.get('Traveller status')); ts = ts if ts in ('Cancelled', 'No-show') else ''
    pd = lambda v: date(v) if isinstance(v, (dt.datetime, dt.date)) else s(v, 20)
    lunch_kip[bid] += num(r.get('Lunch kip'))
    travellers.append((bid, n, s(r.get('First name'), 200), s(r.get('Last name'), 200), s(r.get('Full name'), 200), s(r.get('Country'), 60), s(r.get('Gender'), 10),
        s(r.get('Passport no'), 40), pd(r.get('Passport issued')), pd(r.get('Passport expires')), s(r.get('Food'), 200), s(r.get('Pickup place'), 200), s(r.get('Pickup map'), 300),
        s(m[1], 80), s(m[2] or '', 40), num(r.get('Lunch kip')), ts, s(r.get('Traveller WhatsApp'), 100)))
insert('travellers', ['booking_id', 'n', 'first_name', 'last_name', 'full_name', 'country', 'gender', 'passport_no', 'passport_issued', 'passport_expires', 'food',
    'pickup_place', 'pickup_map', 'lunch_dish', 'lunch_choice', 'lunch_kip', 'status', 'whatsapp'], travellers)
no_trav = len(ids - {t[0] for t in travellers})

# ---------- receipts ----------
LANG = {'English': 'en', 'ລາວ': 'lo', 'ไทย': 'th', '中文': 'zh', '한국어': 'ko', '日本語': 'ja', 'Français': 'fr', 'Deutsch': 'de'}
receipts, nos, with_receipt, keys, highest = [], set(), set(), set(), 0
def new_key():
    while True:
        k = secrets.token_hex(8)
        if k not in keys: keys.add(k); return k
for r in rows('Receipt log'):
    no = receipt_no(r.get('Receipt No')); bid = s(r.get('Booking ID'))
    if not no or bid.upper().startswith('SELFTEST'): continue
    if no in nos: skipped['receipt numbers in the log twice (first kept)'] += 1; continue
    nos.add(no)
    earlier = 1 if s(r.get('Issued by')).startswith('Earlier receipt') else 0
    if not earlier and no.isdigit(): highest = max(highest, int(no))
    key = s(r.get('Form key'))
    if not re.match(r'^[a-f0-9]{16}$', key) or key in keys: key = new_key()
    keys.add(key)
    linked = bid if bid in ids and bid not in with_receipt else None
    if linked: with_receipt.add(bid)
    else: skipped['receipts whose booking ID is in no booking (kept, not linked)'] += 1
    receipts.append((no, date(r.get('Date of issue')) or '2025-01-01', linked, '' if linked else s(bid, 400), LANG.get(s(r.get('Language')), 'en'), num(r.get('Total USD')),
        num(r.get('Total kip')), num(r.get('Deposit USD')), num(r.get('Balance USD')), s(r.get('Issued by'), 120), earlier, key, '{}'))
for b in bookings:   # a number typed on the booking that the log does not have
    if b['receipt'] and b['id'] not in with_receipt:
        if b['receipt'] in nos:   # one paper receipt for several bookings: this booking points to that number
            b['row'] = b['row'][:-1] + (b['receipt'],); skipped['bookings that share another booking\'s receipt number (kept as a reference)'] += 1; continue
        nos.add(b['receipt']); with_receipt.add(b['id'])
        receipts.append((b['receipt'], b['day'], b['id'], '', 'en', 0, 0, 0, 0, 'Earlier receipt (kept)', 1, new_key(), '{}'))
shared = [b for b in bookings if b['row'][-1]]
for b in shared: sql.append(f"UPDATE bookings SET receipt_ref = {q(b['row'][-1])} WHERE id = {q(b['id'])};")
insert('receipts', ['no', 'issued_on', 'booking_id', 'legacy_booking_id', 'language', 'total_usd', 'total_kip', 'deposit_usd', 'balance_usd', 'issued_by', 'earlier',
    'form_key', 'overrides'], receipts)
sql.append(f"UPDATE settings SET value = {q(str(highest + 1))} WHERE `key` = 'receipt_next';")

# ---------- payments: what the Sheet knew as "Amount paid USD", or everything for a booking marked Paid ----------
payments = []
for b in bookings:
    total = round(b['tour_usd'] + (b['transfer_kip'] + lunch_kip[b['id']]) / rate, 2)
    paid = total if b['status'] == 'Paid' and total > b['paid'] else b['paid']
    if paid > 0: payments.append((b['id'], b['day'], paid, 'USD', rate, paid, '', 'Brought over from the Google Sheet', 'Google Sheet'))
insert('payments', ['booking_id', 'paid_on', 'amount', 'currency', 'kip_per_usd', 'amount_usd', 'method', 'note', 'taken_by_name'], payments)

# ---------- agreements, inquiries, reviews, website text, agency share ----------
agreements, seen = [], set()
for r in rows('Agreements'):
    bid = s(r.get('Booking ID')); n = int(num(r.get('Traveller #')))
    if bid.upper().startswith('SELFTEST'): continue
    if bid not in ids: skipped['agreements whose booking is not in Bookings'] += 1; continue
    if (bid, n) in seen: skipped['agreements signed twice for one traveller (first kept)'] += 1; continue
    seen.add((bid, n))
    agreements.append((stamp(r.get('Submitted at')) or '2025-01-01 00:00:00', bid, n, s(r.get('Full name'), 200), s(r.get('Gender'), 10), s(r.get('Nationality'), 60),
        s(r.get('Passport no'), 40), yes(r.get('Photo permission')), s(r.get('Medical / allergies'), 500), s(r.get('Emergency contact'), 80), s(r.get('Emergency phone'), 40),
        s(r.get('Insurance no'), 60), s(r.get('Signed name'), 80), s(r.get('Language'), 5), s(r.get('Form version'), 40), 1 if r.get('Staff checked') in (True, 'TRUE', 'Yes', 1) else 0))
insert('agreements', ['submitted_at', 'booking_id', 'n', 'full_name', 'gender', 'nationality', 'passport_no', 'photo_permission', 'medical', 'ec_name', 'ec_phone', 'insurance',
    'signed_name', 'language', 'form_version', 'staff_checked'], agreements)
IST = {'New', 'Replied', 'Booked', 'Closed'}
inquiries = [(stamp(r.get('Submitted at')) or '2025-01-01 00:00:00', s(r.get('Name'), 80), s(r.get('Contact'), 120), s(r.get('Tour'), 20), s(r.get('Question')), s(r.get('Source'), 40),
    s(r.get('Referrer'), 120), s(r.get('Site language'), 5), s(r.get('Status')) if s(r.get('Status')) in IST else 'New', s(r.get('Staff notes')))
    for r in rows('Inquiries') if not s(r.get('Name')).upper().startswith('SELFTEST')]
insert('inquiries', ['submitted_at', 'name', 'contact', 'tour', 'question', 'source', 'referrer', 'site_language', 'status', 'staff_notes'], inquiries)
reviews = [(1 if r.get('Show') in (True, 'TRUE') else 0, date(r.get('Date')), s(r.get('Name'), 120), s(r.get('Review'))) for r in rows('Reviews') if s(r.get('Review'))]
insert('reviews', ['show', 'review_date', 'name', 'review'], reviews)
CL = [('English (edit this)', 'en'), ('Lao', 'lo'), ('Thai', 'th'), ('Chinese', 'zh'), ('Korean', 'ko'), ('Japanese', 'ja'), ('French', 'fr'), ('German', 'de')]
base = {s(r.get('Key')): r for r in rows('Content base')}; content = []
for r in rows('Content'):
    k = s(r.get('Key'), 80); b = base.get(k)
    if not k or not b: continue
    for col, lang in CL:
        v = s(r.get(col))
        if v and v != s(b.get(col)): content.append((k, lang, v))
insert('content', ['key', 'lang', 'value'], content)
agency = []
AG = ['tour_date', 'booking_id', 'tour', 'guests', 'sending_agency', 'receiving_agency', 'price_usd', 'sender_usd', 'guide_name', 'guide_whatsapp', 'notes', 'accommodation', 'remark']
for r in wb['Agency share'].iter_rows(min_row=6, max_col=13, values_only=True):
    r = list(r) + [None] * 13
    if not any(v not in (None, '') for v in r[:13]): continue
    d = {k: s(r[i]) for i, k in enumerate(AG) if i >= 2}
    d['tour'] = d['tour'][:3] if d['tour'][:3].isdigit() else d['tour']
    agency.append((date(r[0]), s(r[1], 40), json.dumps(d, ensure_ascii=False)))
insert('agency_share', ['tour_date', 'booking_id', 'data'], agency)
inbox = Counter()
for r in rows('Website inbox'):
    st = s(r.get('Status'))
    if st != 'saved' and s(r.get('Booking ID')) not in ids and not s(r.get('Booking ID')).upper().startswith('SELFTEST'): inbox[st.split(':')[0] or 'empty'] += 1

open(out, 'w', encoding='utf-8').write('\n'.join(sql) + '\n')
check = {'bookings': len(bookings), 'travellers': len(travellers), 'receipts': len(receipts), 'receipts linked to a booking': len(with_receipt), 'payments': len(payments),
    'agreements': len(agreements), 'inquiries': len(inquiries), 'reviews': len(reviews), 'tours': len(tours), 'lunch dishes': len(menu), 'website texts changed': len(content),
    'agency rows': len(agency), 'sum tour USD': round(sum(b['tour_usd'] for b in bookings), 2), 'sum transfer kip': round(sum(b['transfer_kip'] for b in bookings)),
    'sum lunch kip': round(sum(lunch_kip.values())), 'sum paid USD': round(sum(p[5] for p in payments), 2), 'next receipt number': str(highest + 1).zfill(6)}
print('SHEET SIDE'); [print(f'  {k}: {v}') for k, v in check.items()]
print('LEFT OUT OR CHANGED'); [print(f'  {k}: {v}') for k, v in skipped.items()] if skipped else print('  nothing')
print(f'  bookings without any traveller row: {no_trav}')
print('WEBSITE INBOX rows not saved and not in Bookings:', dict(inbox) or 'none')
json.dump(check, open(out + '.check.json', 'w'))
